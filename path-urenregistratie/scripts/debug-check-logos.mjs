import { readFile } from 'node:fs/promises';
import { JSDOM } from 'jsdom';
const root = new URL('../', import.meta.url);
const html = await readFile(new URL('index.html', root), 'utf8');
const script = await readFile(new URL('assets/app.js', root), 'utf8');
const smokeScript = script.replace(/function currentCalendarPeriodKey\(\) \{\r?\n  const now = new Date\(\);/, "function currentCalendarPeriodKey() {\n  const now = new Date('2026-08-31T12:00:00.000Z');");
const dom = new JSDOM(html, { runScripts: 'outside-only', url: 'http://localhost:8000/' });
dom.window.fetch = () => new Promise(() => {});
dom.window.requestAnimationFrame = () => 1;
dom.window.cancelAnimationFrame = () => {};
dom.window.eval(smokeScript);
if (typeof dom.window.applyAuthUiMode === 'function') dom.window.applyAuthUiMode('demo');
const sidebar = dom.window.document.querySelector('#sidebar-brand [data-brand-logo]');
const mobile = dom.window.document.querySelector('.mobile-brand-home [data-brand-logo]');
console.log('sidebar src =', sidebar?.src);
console.log('mobile src  =', mobile?.src);
console.log('sidebar dataset eigenLogo =', sidebar?.dataset.eigenLogo);
console.log('mobile dataset eigenLogo =', mobile?.dataset.eigenLogo);
console.log('html data-theme, data-skin =', dom.window.document.documentElement.getAttribute('data-theme'), dom.window.document.documentElement.getAttribute('data-skin'));
